import { EXCLUDED_MEMBERS } from "./recursiveManifestResolver.js";
import { isRegistredEnumType } from "./registredEnums.js";

/** @type {Map<string, { defaults: Set<string>, named: Set<string> }>} */
let resolvedImports = new Map();

function addImport(modulePath, name, asDefault, asAlias) {
  let entry = resolvedImports.get(modulePath);
  if (!entry) {
    entry = { defaults: new Set(), named: new Set() };
    resolvedImports.set(modulePath, entry);
  }
  const hasAlias = asAlias && asAlias !== name;
  if (asDefault) {
    // default imports cannot use `Name as Alias`; the binding name is the alias
    entry.defaults.add(hasAlias ? asAlias : name);
  } else {
    entry.named.add(hasAlias ? `${name} as ${asAlias}` : name);
  }
}

function emitImports() {
  const lines = [];
  for (const [path, { defaults, named }] of resolvedImports) {
    for (const name of [...defaults].sort()) {
      lines.push(`import type ${name} from "${path}";`);
    }
    if (named.size > 0) {
      const sorted = [...named].sort().join(", ");
      lines.push(`import type { ${sorted} } from "${path}";`);
    }
  }
  return lines.join("\n");
}

export function render(clazz) {
  resolvedImports = new Map();
  const eventProps = events(clazz.events);
  const memberProps = members(clazz.members, clazz.attributes);
  const attributeProps = attributes(clazz.attributes, clazz.members);
  return `// DO NOT EDIT this file was generated with scripts/IntrinsicElements
import * as React from "react";

${emitImports()}


export interface ${clazz.name} extends React.HTMLAttributes<HTMLElement> {
${eventProps}
// properties
${memberProps}

// attributes
${attributeProps}

}

declare module 'react' {
  namespace JSX {
    interface IntrinsicElements {
    ${multilineCommentWithReplace(clazz.description)}
      "${clazz.tagName}": ${clazz.name};
    }
  }
}

`;
}

/**
 * build multiline comments
 * @param comment
 */
function multilineCommentWithReplace(comment) {
  if(comment===undefined) {
    return "\n// undocumented";
  }
  const lines = comment.replaceAll("ui5-", "furo-ui5-")
    .replaceAll("@ui5/webcomponents/", "@furo/ui5/")
    .replaceAll("@ui5/webcomponents-fiori/", "@furo/ui5/")
    .split("\n").map(line => " * " + line.trim());
  lines.unshift("\n/**");
  lines.push(" */");
  return lines.join("\n");
}

function attributes(attributes, members) {
  if (attributes) {
    let lines = []
     attributes
      .filter(attr => !EXCLUDED_MEMBERS.has(attr.fieldName) && !EXCLUDED_MEMBERS.has(attr.name))
      .forEach(attr => {
        lines.push(multilineCommentWithReplace(attr.description))
        // get the type from the field members where attr.fieldName == member.name
        // if no field can be found, use the type from attr
        const field = getMemberFieldForAttribute(attr, members);
        // workaround for a very old attribute
        // https://learn.microsoft.com/en-us/previous-versions/windows/internet-explorer/ie-developer/platform-apis/ms537840(v=vs.85)
        if (attr.name === "unselectable") {
          lines.push( `unselectable?:"on" | "off" | undefined`);
        }else{
          lines.push( `"${attr.fieldName || attr.name}"?:${propTyping(field ? field : attr)};`);
        }

      })

      return lines.join("\n");
  }
  return "// no attributes defined.";
}

function members(members, attributes) {
  if (members) {
    let lines = []
     members
      .filter(m => m.privacy == "public" && m.kind == "field")
      .filter(m => !EXCLUDED_MEMBERS.has(m.name))
      .filter(field => isNotAttribute(field, attributes))
      .forEach(m => {
        lines.push(multilineCommentWithReplace(m.description))
        lines.push( `"${m.name}"?:${propTyping(m)};`);
      })
      return lines.join("\n");
  }
  return "// no members defined.";
}

function events(events) {
  if (events) {
    return events
      .map(e => {
        return `"on${e.name}"?:(d:${propTyping(e)})=>void;`;
      })
      .join("\n");
  }
  return "// no events defined.";
}

function isNotAttribute(field, attributes) {
  if (attributes == undefined) {
    return true;
  }
  if (field.attribute) {
    return false;
  }
  let a = attributes.find(attr => {
    return attr.fieldName === field.name;
  });
  return a === undefined;
}

function getMemberFieldForAttribute(attr, members) {
  return members.find(member => {
    return attr.fieldName === member.name;
  });
}

function propTyping(attribute) {
  let type = attribute.type?.text ?? "unknown";
  let rawtype = type;
  const references = attribute.type?.references;

  let isEnum = false;
  if (isRegistredEnumType(type, references)) {
    if (type === "ENUM<T> | undefined") {
      type = "ENUM<unknown>  | keyof typeof ENUM<unknown> | undefined";
    } else {
      type += ` | keyof typeof ${type}`;
    }
    isEnum = true;
  }

  if (attribute.name === "accessibilityAttributes") {
    type = rawtype;
  }
  if (attribute._ui5validator === "CSSColor") {
    type = `CSSProperties['color']`;
  } else if (attribute._ui5validator === "CSSSize") {
    type = `CSSProperties['width'] | CSSProperties['height']`;
  }

  if (type.startsWith("Array")) {
    isEnum = true;
  }
  references?.forEach(ref => {
    const modulePath = ref.package === "@furo/ui5"
      ? `../${ref.module.slice(0, -3).replace("dist/", "")}`
      : `${ref.package}/${ref.module}`;
    addImport(modulePath, ref.name, isEnum, ref.as);
  });

  return type;
}
