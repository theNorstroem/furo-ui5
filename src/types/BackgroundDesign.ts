/**
 * MessageStrip designs.
 * @readonly
 * @enum {string}
 * @public
 */
enum BackgroundDesign {
  /**
   * No background
   * @public
   * @type {Transparent}
   */
  Transparent = "Transparent",
  /**
   * Solid header background
   * @public
   * @type {Solid}
   */
  Solid = "Solid",
  /**
   * List background
   * @public
   * @type {List}
   */
  List = "List",
}
export default BackgroundDesign;
