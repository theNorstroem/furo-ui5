/**
 * Different types of IconShape.
 *
 * @readonly
 * @enum {string}
 * @public
 */
enum IconShape {
  /**
   * Circular shape.
   * @public
   * @type {Circle}
   */
  Circle = "Circle",

  /**
   * Square shape.
   * @public
   * @type {Square}
   */
  Square = "Square",
}

export default IconShape;
