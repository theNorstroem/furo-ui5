/**
 * Different types of IconSize.
 *
 *
 *
 * @readonly
 * @enum {string}
 * @public
 */

enum IconSize {
  /**
   * component size - 2rem
   * font size - 1rem
   * @public
   * @type { XS }
   */
  XS = "XS",

  /**
   * component size - 3rem
   * font size - 1.5rem
   * @public
   * @type { S }
   */
  S = "S",

  /**
   * component size - 4rem
   * font size - 2rem
   * @public
   * @type { M }
   */
  M = "M",

  /**
   * component size - 5rem
   * font size - 2.5rem
   * @public
   * @type { L }
   */
  L = "L",

  /**
   * component size - 7rem
   * font size - 3rem
   * @public
   * @type { XL }
   */
  XL = "XL",
}

export default IconSize;
